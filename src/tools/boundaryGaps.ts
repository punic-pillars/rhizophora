import * as fs from 'fs';
import * as path from 'path';
import { BoundaryGapDetector } from '../engine/BoundaryGapDetector.js';
import { runVeinAnalysis } from '../engine/services/VeinAnalysisService.js';
import { validateFilePath } from '../utils/validateFilePath.js';
import { success, error, type ToolResponse } from './shared.js';
import type { BoundaryGapReport } from '../domain/types/index.js';

type GapMode = 'all' | 'vein-propagation';


export function handleDetectBoundaryGaps(args: {
  filePath: string;
  mode?: GapMode;
  stylesPath?: string;
  designTokens?: number[];
  recursive?: boolean;
}): ToolResponse {
  try {
    const mode = args.mode ?? 'all';
    const designTokens = args.designTokens;
    const recursive = args.recursive ?? false;

    // Validate file existence for single-file modes
    if (!fs.existsSync(args.filePath)) {
      throw new Error(`File not found: "${args.filePath}". Please provide a valid file path.`);
    }

    // Check if filePath is a directory (batch audit mode)
    const isDirectory = fs.statSync(args.filePath).isDirectory();

    if (isDirectory || recursive) {
      return handleBatchAudit(args.filePath, mode, designTokens);
    }

    // Single file mode — validate extension
    validateFilePath(args.filePath);

    const report = runVeinAnalysis(args.filePath, {
      designTokens,
      mode: mode as 'all' | 'vein-propagation',
    });


    return formatModeAwareOutput(report, args.filePath, mode);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return error(`Error detecting boundary gaps: ${message}`);
  }
}

/**
 * v0.8.2: Unified output formatter that respects the requested mode.
 * Uses the mode-aware summary already generated by VeinAnalysisService.convertToReport.
 */
function formatModeAwareOutput(
  report: BoundaryGapReport,
  filePath: string,
  mode: string,
): ToolResponse {
  const lines: string[] = [];
  lines.push(`[BOUNDARY-GAPS] ${filePath}`);

  if (report.gaps.length === 0) {
    lines.push('[CLEAN] No issues detected.');
    lines.push(`[SUMMARY] ${report.summary}`);
    return success(lines.join('\n'));
  }

  for (const gap of report.gaps) {
    const severity = gap.severity.toUpperCase();
    const influence = gap.influenceIndex !== undefined ? ` | Influence: ${gap.influenceIndex}/10` : '';
    lines.push(`[${severity}] ${gap.category} | ${gap.description}${influence}`);
    lines.push(`  Location: ${gap.location}`);
    lines.push(`  Fix: ${gap.suggestion}`);
  }

  lines.push(`[SUMMARY] ${report.summary}`);
  return success(lines.join('\n'));
}

function handleBatchAudit(
  dirPath: string,
  mode: string,
  designTokens?: number[],
): ToolResponse {
  const detector = new BoundaryGapDetector({
    designTokens,
    mode: mode as 'all' | 'vein-propagation',
  });

  const results = detector.batchAudit(dirPath, mode as 'all' | 'vein-propagation');

  const lines: string[] = [];
  lines.push(`[BATCH-AUDIT] ${dirPath} | Mode: ${mode} | Files: ${results.length}`);

  const errorResults = results.filter((r) => r.gapCount === -1);
  const cleanResults = results.filter((r) => r.gapCount === 0);
  const flaggedResults = results.filter((r) => r.gapCount > 0);

  if (flaggedResults.length > 0) {
    lines.push(`[FLAGGED] ${flaggedResults.length} files with issues:`);
    for (const result of flaggedResults) {
      lines.push(`  ${result.file} — ${result.summary}`);
    }
  }

  if (cleanResults.length > 0) {
    lines.push(`[CLEAN] ${cleanResults.length} files`);
  }

  if (errorResults.length > 0) {
    lines.push(`[ERRORS] ${errorResults.length} files:`);
    for (const result of errorResults) {
      lines.push(`  ${result.file} — ${result.summary}`);
    }
  }

  const totalIssues = flaggedResults.reduce((sum, r) => sum + r.gapCount, 0);
  lines.push(`[SUMMARY] ${flaggedResults.length}/${results.length} files have issues (${totalIssues} total gaps)`);

  return success(lines.join('\n'));
}
